export type PageKey = keyof typeof PAGE.en;

export function pageText(language: AppLanguage, key: PageKey, vars?: Record<string, string | number>): string {
  let value: string = PAGE[language][key] ?? PAGE.en[key];
  if (vars) {
    for (const [k, v] of Object.entries(vars)) value = value.replaceAll(`{${k}}`, String(v));
  }
  return value;
}

export function usePage() {
  const language = useAppStore((s) => s.language);
  return (key: PageKey, vars?: Record<string, string | number>) => pageText(language, key, vars);
}

